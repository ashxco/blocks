/**
 * design-system/generated/themes.json: every semantic colour resolved per
 * theme and mode (scripts/check-contrast.mjs), and each theme's identity
 * (scripts/check-themes.mjs).
 */
import { sourcesHash } from "./sources-hash.mjs"
import { all } from "./tokens.mjs"
import { fontFace, themeValue, themes } from "./themes.mjs"
import { themeList } from "./ts.mjs"

const semanticTokens = all.filter((t) => t.meta.tier === "semantic")
const IDENTITY_RADII = [
  "button",
  "button-sm",
  "button-xs",
  "control",
  "card",
  "panel",
  "dialog",
  "overlay",
  "badge",
]

/** component.button.radius-sm for "button-sm". */
const radiusToken = (r) => {
  const [component, size] = r.split("-")
  return `component.${component}.radius${size ? `-${size}` : ""}`
}

/**
 * What makes a theme recognisable, resolved: the accent people see (brand),
 * its scale and the neutral scale at their middle steps, the component radii,
 * and the font names and genres.
 */
function themeIdentity(theme) {
  return {
    accent: {
      brand: Object.fromEntries(
        theme.modes.map((mode) => [
          mode,
          themeValue(theme, "color.brand", mode),
        ])
      ),
      scale: themeValue(theme, "theme.accent.600"),
    },
    neutral: {
      500: themeValue(theme, "theme.neutral.500"),
      900: themeValue(theme, "theme.neutral.900"),
    },
    radius: Object.fromEntries(
      IDENTITY_RADII.map((r) => [r, themeValue(theme, radiusToken(r))])
    ),
    fonts: themeList.find((t) => t.id === theme.id).fonts,
    genres: Object.fromEntries(
      ["heading", "sans", "mono"].map((kind) => [
        kind,
        fontFace(theme, `font.family.${kind}`).genre,
      ])
    ),
  }
}

export const themesJson = `${JSON.stringify(
  {
    $comment:
      "GENERATED by design-system/build.mjs. Do not edit. Every semantic colour, resolved per theme and mode (scripts/check-contrast.mjs), and each theme's identity (scripts/check-themes.mjs).",
    sources: await sourcesHash(),
    themes: themes.map((theme) => ({
      id: theme.id,
      name: theme.name,
      identity: themeIdentity(theme),
      modes: Object.fromEntries(
        theme.modes.map((mode) => [
          mode,
          Object.fromEntries(
            semanticTokens.map((t) => [
              t.meta.cssVar.slice(2),
              themeValue(theme, t.path.join("."), mode),
            ])
          ),
        ])
      ),
    })),
  },
  null,
  2
)}\n`
