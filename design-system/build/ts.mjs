/** design-system/generated/tokens.ts: the typed token and theme list for the viewer. */
import { DEFAULT_THEME, MODES, files } from "./load.mjs"
import {
  breakpointNames,
  breakpoints,
  breakpointsByToken,
  responsiveVars,
} from "./breakpoints.mjs"
import {
  all,
  byPath,
  darkByPath,
  px,
  refOf,
  resolvedValue,
  round,
} from "./tokens.mjs"
import { fontFace, resolved, themeValue, themes } from "./themes.mjs"

/** A token's value and reference, and its dark ones for a semantic token: DesignToken's value/ref/dark. */
const valueOf = (light, dark, isMode) => ({
  value: resolvedValue(light),
  ref: refOf(light),
  dark: isMode ? { value: resolvedValue(dark), ref: refOf(dark) } : undefined,
})

const tokenValue = (themeId, name) =>
  valueOf(
    resolved[themeId].light.get(name),
    resolved[themeId].dark.get(name),
    byPath.get(name).meta.scope === "mode"
  )

/** Drops undefined members, the way the generated JSON does. */
const plain = (v) => JSON.parse(JSON.stringify(v))

const themedNames = new Set()
const themeValues = new Map()
for (const theme of themes) {
  const values = {}
  for (const name of byPath.keys()) {
    const v = tokenValue(theme.id, name)
    if (JSON.stringify(v) !== JSON.stringify(tokenValue(DEFAULT_THEME, name))) {
      values[name] = plain(v)
      themedNames.add(name)
    }
  }
  themeValues.set(theme.id, values)
}

export const list = all.map((t) => {
  const name = t.path.join(".")
  const steps = breakpointsByToken.get(name)
  return {
    name,
    cssVar: t.meta.cssVar,
    tier: t.meta.tier,
    group: t.meta.group,
    type: t.$type,
    ...valueOf(t, darkByPath.get(name), t.meta.scope === "mode"),
    breakpoints: steps
      ? Object.fromEntries(steps.map((s) => [s.name, s.value]))
      : undefined,
    themed: themedNames.has(name) || undefined,
    utility: t.meta.utility,
    description: t.$description,
  }
})

const radiusLabel = (v) => (px(v) >= 999 ? "pill" : `${round(px(v))}px`)

const RADII = ["button", "control", "card", "panel", "dialog"]

/** Each theme as tokens.ts lists it. */
export const themeList = themes.map((theme) => {
  const swatches = Object.fromEntries(
    MODES.map((mode) => [
      mode,
      {
        accent: themeValue(theme, "color.brand", mode),
        neutral: themeValue(theme, "color.muted-foreground", mode),
        background: themeValue(theme, "color.background", mode),
        foreground: themeValue(theme, "color.foreground", mode),
        panel: themeValue(theme, "color.panel", mode),
      },
    ])
  )
  const radius = Object.fromEntries(
    RADII.map((r) => [r, themeValue(theme, `component.${r}.radius`)])
  )
  const buttons =
    px(radius.button) >= 999
      ? "Pill buttons"
      : `${radiusLabel(radius.button)} buttons`
  return {
    id: theme.id,
    name: theme.name,
    description: theme.description,
    default: theme.id === DEFAULT_THEME,
    modes: theme.modes,
    swatches,
    radius: {
      ...radius,
      summary: `${buttons}, ${radiusLabel(radius.control)} controls, ${radiusLabel(radius.card)} cards`,
    },
    fonts: Object.fromEntries(
      ["heading", "sans", "mono"].map((kind) => [
        kind,
        fontFace(theme, `font.family.${kind}`).name,
      ])
    ),
    overrides: [...new Set(Object.values(theme.overrides).flat())],
    values: themeValues.get(theme.id),
  }
})

/** The system grid per breakpoint: { columns: { base: 4, md: 8, lg: 12 }, gutter: { … } }. */
const gridSummary = Object.fromEntries(
  ["columns", "gutter"].map((key) => {
    const t = byPath.get(`grid.${key}`)
    if (!t)
      throw new Error(
        `grid.${key} is missing from ${files.layout}: <Grid> and the grid-system utility read it`
      )
    const steps = breakpointsByToken.get(`grid.${key}`) ?? []
    return [
      key,
      {
        base: t.$value,
        ...Object.fromEntries(steps.map((step) => [step.name, step.value])),
      },
    ]
  })
)
if (
  typeof gridSummary.columns.base !== "number" ||
  Object.values(gridSummary.columns).some(
    (n) => !Number.isInteger(n) || n < 1 || n > 12
  )
) {
  throw new Error(
    "grid.columns: give a whole number of columns from 1 to 12 at every breakpoint"
  )
}

const typeRoles = all
  .filter((t) => t.meta.tier === "typography" && t.meta.group === "roles")
  .map((t) => t.path[1])

export const ts = `// GENERATED by design-system/build.mjs. Do not edit.
// Change tokens in design-system/tokens/*.tokens.json or design-system/themes/*.tokens.json,
// then run \`npm run tokens\`.

export type TokenTier = "primitive" | "semantic" | "typography" | "layout" | "component"

export type Breakpoint = ${breakpointNames.map((n) => JSON.stringify(n)).join(" | ")}

/** System breakpoints, smallest first, with the viewport width each starts at. */
export const breakpoints: readonly { name: Breakpoint; min: string }[] = ${JSON.stringify(breakpoints)}

export interface DesignToken {
  /** Dot path in the token source, e.g. "color.brand". */
  name: string
  /** CSS custom property, e.g. "--brand". */
  cssVar: string
  tier: TokenTier
  group: string
  /** DTCG $type. */
  type: string
  /** Resolved value in the default theme (light mode for semantic tokens). */
  value: unknown
  /** Token this one references, if any. */
  ref?: string
  /** Dark-mode value for semantic tokens. */
  dark?: { value: unknown; ref?: string }
  /**
   * Values from a breakpoint up, for tokens that change with the viewport.
   * \`value\` is the base (phones); each entry is the full value from that
   * breakpoint's min width until the next one listed.
   */
  breakpoints?: Partial<Record<Breakpoint, unknown>>
  /** True when some theme gives this token another value (see themes[].values). */
  themed?: boolean
  /** How to use it in Tailwind. */
  utility?: string
  description?: string
}

export const tokens: DesignToken[] = ${JSON.stringify(list.map(plain), null, 2)}

export const tokensByTier = (tier: TokenTier) => tokens.filter((t) => t.tier === tier)

/**
 * The CSS variables that change with the viewport: every one at its base
 * value, and the ones each breakpoint overrides from its min width up.
 * tokens.css applies them with @media; device previews in the viewer apply
 * them for the previewed width, which media queries cannot see.
 */
export const responsiveVars: {
  base: Record<string, string>
  breakpoints: readonly { name: Breakpoint; min: string; vars: Record<string, string> }[]
} = ${JSON.stringify(responsiveVars, null, 2)}

/**
 * The system grid (grid.* in layout.tokens.json) per breakpoint, mobile first:
 * \`base\` is phones, each breakpoint listed holds from its min width up.
 * <Grid> reads the column counts to keep spans inside the grid.
 */
export const grid: {
  columns: { base: number } & Partial<Record<Breakpoint, number>>
  gutter: { base: string } & Partial<Record<Breakpoint, string>>
} = ${JSON.stringify(gridSummary, null, 2)}

/** Type role names (text-<role> utilities). Used by cn() so roles merge as font sizes. */
export const typeRoles = ${JSON.stringify(typeRoles)} as const

/* -------------------------------------------------------------------------- */
/* Themes                                                                      */
/* -------------------------------------------------------------------------- */

/** Theme preset ids, in picker order. data-theme="<id>" applies one. */
export const themeIds = ${JSON.stringify(themes.map((t) => t.id))} as const

export type ThemeId = (typeof themeIds)[number]

/** Light or dark. Independent of the theme: every theme supports both. */
export type ThemeMode = "light" | "dark"

/** The theme used when no data-theme is set. */
export const defaultThemeId: ThemeId = ${JSON.stringify(DEFAULT_THEME)}

/** A token's value under one theme, shaped like DesignToken's value, ref and dark. */
export interface ThemeTokenValue {
  value: unknown
  ref?: string
  dark?: { value: unknown; ref?: string }
}

export interface ThemeSwatches {
  /** The brand colour (links, focus, highlights). */
  accent: string
  /** A mid neutral (muted-foreground), showing the neutral's tint. */
  neutral: string
  background: string
  foreground: string
  panel: string
}

export interface Theme {
  id: ThemeId
  name: string
  /** One line on what the theme looks like. */
  description: string
  /** True for the default theme. */
  default: boolean
  /** The modes the theme supports. */
  modes: readonly ThemeMode[]
  /** Resolved OKLCH colours per mode, for pickers and previews. */
  swatches: Record<ThemeMode, ThemeSwatches>
  /** Resolved component radii, plus a one-line summary such as "Pill buttons, 12px controls, 18px cards". */
  radius: { button: string; control: string; card: string; panel: string; dialog: string; summary: string }
  /** Font family names: heading (display and heading roles, h1 to h6), sans (UI and body) and mono. */
  fonts: { heading: string; sans: string; mono: string }
  /** Token names the theme file sets. */
  overrides: readonly string[]
  /**
   * Every token whose value under this theme differs from the default theme
   * (what the theme sets and everything that follows from it), by token name.
   * Tokens not listed have their default value (tokens[].value / .dark).
   */
  values: Readonly<Record<string, ThemeTokenValue>>
}

export const themes: readonly Theme[] = ${JSON.stringify(themeList, null, 2)}

/** A token's value under a theme: its theme value when it has one, else the default. */
export function tokenValueIn(theme: ThemeId, token: DesignToken): ThemeTokenValue {
  return themes.find((t) => t.id === theme)?.values[token.name] ?? { value: token.value, ref: token.ref, dark: token.dark }
}
`
