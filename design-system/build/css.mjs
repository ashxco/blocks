/**
 * app/styles/tokens.css: Tailwind v4 @theme, :root, the mode and theme
 * scopes, the fonts of the type roles and the breakpoint values.
 *
 * Role fonts. Tailwind's text-<role> utility sets size, line height, tracking
 * and weight, never a font. A role whose fontFamily references a family other
 * than font.family.sans (hero … title read font.family.heading, code reads
 * font.family.mono) gets a font-family too, written as an @utility that
 * Tailwind merges into the same rule. It reads var(--bk-font-family, <font>):
 * font-sans, font-heading and font-mono set --bk-font-family, a property that
 * does not inherit, so a font utility on the same element wins over the role
 * (font-mono text-h3) while a parent's never reaches it. The sans roles set
 * no font and inherit as before; a heading element (h1 to h6, which take the
 * heading face in globals.css) given one of them takes the sans font.
 */
import { DEFAULT_THEME, isReference, refName } from "./load.mjs"
import { responsiveVars } from "./breakpoints.mjs"
import { all, byPath } from "./tokens.mjs"
import { themes } from "./themes.mjs"
import {
  ON_DARK,
  ON_LIGHT,
  modeDependents,
  ordered,
  rootDecls,
  rootExpr,
  systemAliases,
  themeDeclsById,
  themeDependents,
  themeInputs,
  themeLines,
} from "./scopes.mjs"

const SANS_FAMILY = "font.family.sans"
/** The variable font utilities set and font-setting roles read first; it does not inherit. */
const ROLE_FONT_VAR = "--bk-font-family"

const fontFamilies = all.filter((t) => t.meta.group === "font-family")

/** Each type role and the font family token it uses: { role, family: "font.family.heading", cssVar }. */
const roleFonts = all
  .filter((t) => t.meta.tier === "typography" && t.meta.group === "roles")
  .map((t) => {
    const family = t.original.$value.fontFamily
    const target = isReference(family) ? byPath.get(refName(family)) : undefined
    if (target?.meta.group !== "font-family") {
      throw new Error(
        `type.${t.path[1]}: fontFamily must reference a font family token, such as {font.family.heading}`
      )
    }
    return {
      role: t.path[1],
      family: refName(family),
      cssVar: target.meta.cssVar,
    }
  })
const fontRoles = roleFonts.filter((r) => r.family !== SANS_FAMILY)
const sansRoles = roleFonts.filter((r) => r.family === SANS_FAMILY)

const roleFontCss = `/* Role fonts. text-<role> sets size, line height, tracking and weight; the
   roles below also set their font, so a heading role on any element (a div,
   a span, a button) renders in the theme's heading face.
   ${ROLE_FONT_VAR} lets a font utility on the same element win
   (font-mono text-h3); it does not inherit, so a parent's font utility never
   reaches a role. */
@property ${ROLE_FONT_VAR} {
  syntax: "*";
  inherits: false;
}

${fontFamilies
  .map(
    (t) => `@utility ${t.meta.utility} {
  ${ROLE_FONT_VAR}: var(${t.meta.cssVar});
}`
  )
  .join("\n\n")}

${fontRoles
  .map(
    (r) => `@utility text-${r.role} {
  font-family: var(${ROLE_FONT_VAR}, var(${r.cssVar}));
}`
  )
  .join("\n\n")}

/* h1 to h6 take the heading face (globals.css). One given a role that sets no
   font, such as text-label, takes the sans font like that role anywhere else. */
@layer base {
  :where(h1, h2, h3, h4, h5, h6):is(${sansRoles.map((r) => `.text-${r.role}`).join(", ")}) {
    font-family: var(${byPath.get(SANS_FAMILY).meta.cssVar});
  }
}`

const decl = ([v, value], indent = "  ") => `${indent}${v}: ${value};`
const decls = (list, indent) => list.map((d) => decl(d, indent)).join("\n")
/** The root declarations of `vars`, in source order. */
const declsOf = (vars) => decls(ordered(vars).map((v) => [v, rootExpr.get(v)]))

const semanticColors = all
  .filter((t) => t.meta.tier === "semantic")
  .map((t) => t.meta.cssVar)

const mediaBlocks = responsiveVars.breakpoints.map(
  (b) => `@media (width >= ${b.min}) {
  :root {
${decls(Object.entries(b.vars), "    ")}
  }
}`
)

const themeBlocks = themes
  .filter((t) => themeDeclsById.get(t.id).size > 0)
  .map((t) => {
    const scope = themeDeclsById.get(t.id)
    return `/* ${t.name}. ${t.description} */
[data-theme="${t.id}"] {
${decls(ordered(scope.keys()).map((v) => [v, scope.get(v)]))}
}`
  })

export const css = `/*
 * GENERATED by design-system/build.mjs. Do not edit.
 * Change tokens in design-system/tokens/*.tokens.json or design-system/themes/*.tokens.json,
 * then run \`npm run tokens\`.
 */

/* Tailwind's default palette, shadows, fonts and scales are removed:
   only Blocks tokens produce utilities. */
@theme static {
  --color-*: initial;
  --shadow-*: initial;
  --inset-shadow-*: initial;
  --drop-shadow-*: initial;
  --text-shadow-*: initial;
  --font-*: initial;
  --text-*: initial;
  --radius-*: initial;
  --ease-*: initial;
  --blur-*: initial;
  --breakpoint-*: initial;
${decls(systemAliases)}
  --default-transition-duration: var(--duration-fast);
  --default-transition-timing-function: var(--ease-standard);
${decls(themeLines)}
}

/* Semantic colours become utilities (bg-brand, text-body, border-border…)
   that follow the active mode and theme. */
@theme inline {
  --color-transparent: transparent;
  --color-current: currentColor;
  --color-white: var(--bk-neutral-0);
  --color-black: var(--bk-neutral-1000);
${semanticColors.map((v) => `  --color-${v.slice(2)}: var(${v});`).join("\n")}
}

${roleFontCss}

:root {
  /* Primitives. --bk-accent-* and --bk-neutral-* are the theme's scales. */
${decls(rootDecls.primitive)}

  /* Mode switches: var(${ON_LIGHT}, x) is x in light mode and nothing in
     dark mode; var(${ON_DARK}, x) the other way round. */
  ${ON_LIGHT}: initial;
  ${ON_DARK}: ;
${
  rootDecls.sources.length
    ? `
  /* Light and dark sources of the semantic colours a theme sets directly */
${decls(rootDecls.sources)}
`
    : ""
}
  /* Semantic colours, light and dark */
${decls(rootDecls.semantic)}

  /* Layout and motion */
${decls(rootDecls.layout)}

  /* Component tokens */
${decls(rootDecls.component)}
}

/* Modes. .dark and .light switch the mode of their subtree (.light wins
   inside .dark and the other way round); everything that reads the switches
   is evaluated again in the scope. */
.dark {
  color-scheme: dark;
  ${ON_LIGHT}: ;
  ${ON_DARK}: initial;
}

.light {
  color-scheme: light;
  ${ON_LIGHT}: initial;
  ${ON_DARK}: ;
}

.dark,
.light {
${declsOf(modeDependents)}
}

/* Themes. data-theme="<id>" scopes a theme to its subtree; no attribute means
   ${DEFAULT_THEME}. Every theme scope starts from the default theme… */
[data-theme] {
${declsOf(themeInputs)}
}

/* …takes its theme's values… */
${themeBlocks.join("\n\n")}

/* …and evaluates everything that depends on them again, in the subtree's mode. */
[data-theme] {
${declsOf(themeDependents)}
}
${
  mediaBlocks.length
    ? `
/* Breakpoint values ($extensions.blocks.breakpoints in the token sources):
   the base values above apply on phones, these from each breakpoint up. */
${mediaBlocks.join("\n\n")}
`
    : ""
}`
